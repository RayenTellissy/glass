#!/usr/bin/env python3
"""Lists the third-party components Glass ships, for the About dialog and installers.

Usage:
  scripts/licences/third-party.py            rewrite assets/licences/third-party.tsv
  scripts/licences/third-party.py --check    exit 1 when the file is out of date
  scripts/licences/third-party.py --texts FILE
                                             write the licence texts of every shipped
                                             crate, read from the crates' own sources,
                                             into FILE (for the installers)

The list comes from `cargo metadata` with the release features (`app/release-full`)
for every target platform, plus the native libraries pinned in
scripts/ffmpeg/versions.env. A crate ships when the `app` crate reaches it through
normal dependencies without passing through a proc-macro; build and dev dependencies
and proc-macros run only while compiling and are listed as `dev` so the file still
names every registry package in Cargo.lock (a test in the `assets` crate compares
the two). Python standard library only.
"""

import json
import os
import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
OUT = REPO / "assets" / "licences" / "third-party.tsv"
VERSIONS = REPO / "scripts" / "ffmpeg" / "versions.env"
FEATURES = "app/release-full"
DESCRIPTION_MAX = 120
TEXT_FILE = re.compile(r"^(licen[cs]e|copying|notice|unlicense|copyright)", re.IGNORECASE)

# The native libraries the release build bundles: name, versions.env key, SPDX
# licence, project page. FFmpeg is configured with --enable-gpl --enable-version3.
NATIVE = [
    ("FFmpeg", "FFMPEG_VERSION", "GPL-3.0-or-later", "https://ffmpeg.org"),
    ("x264", "X264_COMMIT", "GPL-2.0-or-later", "https://code.videolan.org/videolan/x264"),
    ("x265", "X265_VERSION", "GPL-2.0-or-later", "https://bitbucket.org/multicoreware/x265_git"),
    ("dav1d", "DAV1D_VERSION", "BSD-2-Clause", "https://code.videolan.org/videolan/dav1d"),
    ("nv-codec-headers", "NVCODEC_VERSION", "MIT", "https://github.com/FFmpeg/nv-codec-headers"),
    ("zlib", "ZLIB_VERSION", "Zlib", "https://zlib.net"),
]

HEADER = """\
# Third-party components of Glass release builds. Generated by
# scripts/licences/third-party.py from `cargo metadata` and scripts/ffmpeg/versions.env;
# do not edit. Columns (tab-separated): kind, name, version, SPDX licence, repository,
# description. kind is native (bundled library), crate (compiled into the app) or dev
# (build, dev and proc-macro crates, which do not ship and carry only name and version).
"""


def metadata():
    cargo = os.environ.get("CARGO", "cargo")
    out = subprocess.run(
        [cargo, "metadata", "--format-version", "1", "--locked", "--features", FEATURES],
        cwd=REPO,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def shipped_ids(meta):
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == "app" and p["source"] is None)
    seen = set()
    stack = [root]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if not any(k["kind"] is None for k in dep["dep_kinds"]):
                continue
            target = packages[dep["pkg"]]
            if any("proc-macro" in t["kind"] for t in target["targets"]):
                continue
            stack.append(dep["pkg"])
    return {pid for pid in seen if packages[pid]["source"] is not None}


def clean(text):
    return " ".join((text or "").split())


def short(text):
    text = clean(text)
    if len(text) <= DESCRIPTION_MAX:
        return text
    return text[: DESCRIPTION_MAX - 1].rstrip() + "…"


def versions():
    values = {}
    for line in VERSIONS.read_text().splitlines():
        m = re.match(r'^([A-Z0-9_]+)="(.*)"$', line.strip())
        if m:
            values[m.group(1)] = m.group(2)
    return values


def rows(meta):
    pins = versions()
    out = []
    for name, key, licence, repo in NATIVE:
        version = pins[key]
        if key.endswith("_COMMIT"):
            version = version[:7]
        out.append(("native", name, version, licence, repo, ""))
    ships = shipped_ids(meta)
    crates = sorted(
        (p for p in meta["packages"] if p["source"] is not None),
        key=lambda p: (p["name"].lower(), p["version"]),
    )
    for p in crates:
        if p["id"] in ships:
            repo = clean(p.get("repository")) or clean(p.get("homepage"))
            repo = repo or f"https://crates.io/crates/{p['name']}/{p['version']}"
            licence = clean(p.get("license")) or "LicenseRef-see-crate"
            out.append(("crate", p["name"], p["version"], licence, repo, short(p.get("description"))))
        else:
            out.append(("dev", p["name"], p["version"], "", "", ""))
    return out


def render(table):
    lines = [HEADER]
    for row in table:
        lines.append("\t".join(row).rstrip("\t") + "\n")
    return "".join(lines)


def write_texts(meta, path):
    ships = shipped_ids(meta)
    packages = sorted(
        (p for p in meta["packages"] if p["id"] in ships),
        key=lambda p: (p["name"].lower(), p["version"]),
    )
    parts = [
        "Licence texts of the Rust crates compiled into Glass, copied from each crate's\n"
        "published source. The bundled native libraries' texts are the other files in\n"
        "this folder.\n"
    ]
    missing = []
    # Identical texts (the Apache licence appears some hundred times) are written once.
    first_seen = {}
    for p in packages:
        folder = pathlib.Path(p["manifest_path"]).parent
        files = sorted(f for f in folder.iterdir() if f.is_file() and TEXT_FILE.match(f.name))
        rule = "=" * 78
        parts.append(f"\n{rule}\n{p['name']} {p['version']} ({clean(p.get('license'))})\n{rule}\n")
        if not files:
            missing.append(p["name"])
            parts.append(
                f"\nThis crate publishes no licence file. It is licensed under "
                f"{clean(p.get('license'))}; see {clean(p.get('repository')) or 'crates.io'}.\n"
            )
        for f in files:
            text = f.read_text(errors="replace").rstrip()
            owner = first_seen.setdefault(text, f"{p['name']} {p['version']}")
            if owner == f"{p['name']} {p['version']}":
                parts.append(f"\n--- {f.name} ---\n\n{text}\n")
            else:
                parts.append(f"\n--- {f.name}: the same text as under {owner} above ---\n")
    pathlib.Path(path).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(path).write_text("".join(parts))
    print(f"third-party.py: {len(packages)} crates, {len(missing)} without a licence file -> {path}")


def main(argv):
    if argv[:1] == ["--texts"] and len(argv) == 2:
        write_texts(metadata(), argv[1])
        return 0
    if argv not in ([], ["--check"]):
        print(__doc__, file=sys.stderr)
        return 2
    text = render(rows(metadata()))
    if argv == ["--check"]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"third-party.py: {OUT.relative_to(REPO)} is out of date; run scripts/licences/third-party.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"third-party.py: wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
